/** 为指定数据源生成一批仿真文章（确定性伪随机，便于去重联调） */
export function generateMockArticles(
  sourceId: string,
  mediaName: string,
  count: number
): IngestArticle[] {
  const now = Date.now();
  const articles: IngestArticle[] = [];
  for (let i = 0; i < count; i++) {
    // 用 sourceId + i 做稳定选片，同一数据源多次推送只产出固定文章，
    // 便于验证「重复推送自动去重」
    const topic = MOCK_TOPICS[hashPick(`${sourceId}-${i}`, MOCK_TOPICS.length)];
    const slug = `${sourceId.slice(0, 8)}-${i + 1}`;
    articles.push({
      title: topic.headline,
      url: `https://mock-ingest.local/${mediaName ? encodeURIComponent(mediaName) : "media"}/${slug}.html`,
      publishedAt: new Date(now - i * 3600_000).toISOString(),
      content: `${topic.body}（${mediaName || "本报"} 讯）`,
    });
  }
  return articles;
}

function hashPick(seed: string, mod: number): number {
  let h = 0;
  for (let i = 0; i < seed.length; i++) h = (h * 31 + seed.charCodeAt(i)) >>> 0;
  return h % mod;
}
